using System;
using System.Collections.Generic;
using System.Text;
using MajSimai.CppGen.Abi;

namespace MajSimai.CppGen.Emit;

/// <summary>
/// Builds C++ source text with four-space indentation, <c>\n</c> line endings and Doxygen comments.
/// </summary>
internal sealed class CppWriter
{
    /// <summary>
    /// The longest line a documentation comment is wrapped to.
    /// </summary>
    private const int MaxLineLength = 120;

    /// <summary>
    /// The text written so far.
    /// </summary>
    private readonly StringBuilder _builder = new();

    /// <summary>
    /// The current indentation depth.
    /// </summary>
    private int _depth;

    /// <summary>
    /// Writes the comment every generated file starts with.
    /// </summary>
    /// <param name="version">The version of MajSimai the file was generated from.</param>
    /// <param name="commentPrefix">The comment marker of the language, such as <c>//</c> or <c>#</c>.</param>
    public void Banner(string version, string commentPrefix = "//")
    {
        Line($"{commentPrefix} <auto-generated>");
        Line($"{commentPrefix} Generated by MajSimai.CppGen from the native ABI of MajSimai {version}.");
        Line($"{commentPrefix} Do not edit this file: change Runtime/Unmanaged, then run `dotnet run --project tools/MajSimai.CppGen`.");
        Line($"{commentPrefix} </auto-generated>");
    }

    /// <summary>
    /// Writes a line at the current indentation, or an empty line.
    /// </summary>
    /// <param name="text">The text of the line.</param>
    public void Line(string text = "")
    {
        if (text.Length != 0)
        {
            _builder.Append(' ', _depth * 4);
            _builder.Append(text);
        }
        _builder.Append('\n');
    }

    /// <summary>
    /// Writes a label such as <c>public:</c> one level less indented than the current block.
    /// </summary>
    /// <param name="text">The label.</param>
    public void Label(string text)
    {
        _builder.Append(' ', Math.Max(0, _depth - 1) * 4);
        _builder.Append(text);
        _builder.Append('\n');
    }

    /// <summary>
    /// Writes several lines at the current indentation, keeping their relative indentation.
    /// </summary>
    /// <param name="text">The lines, separated by <c>\n</c>.</param>
    public void Lines(string text)
    {
        foreach (var line in text.Replace("\r\n", "\n").Split('\n'))
        {
            Line(line);
        }
    }

    /// <summary>
    /// Writes <c>{</c>, indents until the returned object is disposed, then writes the closing text.
    /// </summary>
    /// <param name="closing">The closing text, such as <c>}</c> or <c>};</c>.</param>
    /// <returns>An object that ends the block when disposed.</returns>
    public IDisposable Block(string closing = "}")
    {
        Line("{");
        _depth++;

        return new BlockEnd(this, closing);
    }

    /// <summary>
    /// Writes a documentation comment wrapped to the line length, or nothing for empty text.
    /// </summary>
    /// <param name="text">The text.</param>
    public void Doc(string text)
    {
        if (text.Length == 0)
        {
            return;
        }
        var width = Math.Max(40, MaxLineLength - (_depth * 4) - 4);
        foreach (var line in Wrap(text, width))
        {
            Line("/// " + line);
        }
    }

    /// <summary>
    /// Writes the documentation of a function: its summary, its parameters and its return value.
    /// </summary>
    /// <param name="doc">The documentation.</param>
    /// <param name="parameterNames">The names of the parameters, in order.</param>
    public void Doc(DocComment doc, IEnumerable<string> parameterNames)
    {
        Doc(doc.Summary);
        foreach (var name in parameterNames)
        {
            var text = doc.GetParameter(name);
            if (text.Length != 0)
            {
                Doc($"@param {name} {text}");
            }
        }
        if (doc.Returns.Length != 0)
        {
            Doc($"@return {doc.Returns}");
        }
    }

    /// <inheritdoc/>
    public override string ToString()
    {
        return _builder.ToString();
    }

    /// <summary>
    /// Splits text into lines of at most <paramref name="width"/> characters at spaces. A word longer than the width
    /// gets a line of its own.
    /// </summary>
    /// <param name="text">The text.</param>
    /// <param name="width">The longest line.</param>
    /// <returns>The lines.</returns>
    private static IEnumerable<string> Wrap(string text, int width)
    {
        var line = new StringBuilder();
        foreach (var word in text.Split(' ', StringSplitOptions.RemoveEmptyEntries))
        {
            if (line.Length != 0 && line.Length + 1 + word.Length > width)
            {
                yield return line.ToString();
                line.Clear();
            }
            if (line.Length != 0)
            {
                line.Append(' ');
            }
            line.Append(word);
        }
        if (line.Length != 0)
        {
            yield return line.ToString();
        }
    }

    /// <summary>
    /// Ends a block started by <see cref="Block"/>.
    /// </summary>
    /// <param name="writer">The writer.</param>
    /// <param name="closing">The closing text.</param>
    private sealed class BlockEnd(CppWriter writer, string closing) : IDisposable
    {
        /// <summary>
        /// Whether the block was already ended.
        /// </summary>
        private bool _ended;

        /// <summary>
        /// Removes one level of indentation and writes the closing text.
        /// </summary>
        public void Dispose()
        {
            if (_ended)
            {
                return;
            }
            _ended = true;
            writer._depth--;
            writer.Line(closing);
        }
    }
}
