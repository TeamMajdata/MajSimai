"""Publishes MajSimai as a native AOT shared or static library and packages it with the generated C++ wrapper.

Usage:
    python tools/build-cpp-package.py --kind shared|static [--rid <rid>] [--output <folder>] [--version <version>] [--verify]

The package is a CMake project that a C++17 program adds with add_subdirectory() and links as MajSimai::MajSimaiCpp:

    CMakeLists.txt         the interface target MajSimai::MajSimaiCpp, linked to the imported target MajSimai::Native
    MajSimaiNative.json    what was built: the kind, the runtime identifier and the link items
    include/MajSimai/      the C++ wrapper, generated by tools/MajSimai.CppGen
    lib/                   MajSimai.so or MajSimai.dylib (shared), MajSimai.a (static), MajSimai.lib (Windows)
    lib/aot/               static only: the native AOT runtime the static library needs
    bin/                   Windows shared only: MajSimai.dll

A static library needs the native AOT runtime and some system libraries after it on the link line; the script reads
them from the publish itself (tools/MajSimai.NativePackage.targets), so the package matches the .NET SDK that built it.

It needs the .NET 10 SDK and the native AOT prerequisites of the platform (a C++ toolchain); --verify also needs CMake.
Native AOT cannot cross-compile to another operating system, so build on the platform you target.
"""
import argparse
import json
import platform
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parent.parent
PROJECT = REPOSITORY / "MajSimai.csproj"
GENERATOR = REPOSITORY / "tools" / "MajSimai.CppGen"
LINK_TARGETS = REPOSITORY / "tools" / "MajSimai.NativePackage.targets"
MANIFEST = "MajSimaiNative.json"
APPLE_PREFIXES = ("osx", "ios", "tvos", "maccatalyst")

VERIFY_PROGRAM = r"""#include <MajSimai/MajSimai.h>

#include <iostream>

int main()
{
    const auto file = MajSimai::SimaiParser::Parse("&title=Verify\n&inote_1=(120){4}1-3[8:1]*-5[8:1],2,\n");
    const auto& notes = file.charts[0].noteTimings[0].notes;
    if (file.title != "Verify" || notes.size() != 3 || !notes[0].isStar || notes[0].relatedNotes.size() != 2)
    {
        std::cerr << "The parsed file is not the expected one.\n";
        return 1;
    }
    try
    {
        MajSimai::SimaiParser::Parse("&inote_1=(120)1,{4", MajSimai::SimaiSyntaxTolerance::Strict);
        std::cerr << "Strict mode accepted an unclosed declaration.\n";
        return 1;
    }
    catch (const MajSimai::SimaiParseException& e)
    {
        if (e.GetCode() != MajSimai::SimaiParseErrorCode::InvalidSimaiSyntax)
        {
            std::cerr << "Strict mode failed with the wrong code: " << e.what() << '\n';
            return 1;
        }
    }
    std::cout << "The MajSimai C++ package works.\n";
    return 0;
}
"""


def fail(message):
    print(f"error: {message}", file=sys.stderr)
    sys.exit(1)


def run(command, cwd=None):
    print("> " + " ".join(str(part) for part in command), flush=True)
    result = subprocess.run([str(part) for part in command], cwd=cwd)
    if result.returncode != 0:
        fail(f"the command above failed with exit code {result.returncode}")


def host_runtime_identifier():
    """Gets the .NET runtime identifier of this computer, such as linux-x64."""
    systems = {"Linux": "linux", "Darwin": "osx", "Windows": "win"}
    architectures = {"x86_64": "x64", "amd64": "x64", "aarch64": "arm64", "arm64": "arm64", "i386": "x86", "i686": "x86", "x86": "x86"}
    system = systems.get(platform.system())
    architecture = architectures.get(platform.machine().lower())
    if system is None or architecture is None:
        fail(f"cannot tell the runtime identifier of {platform.system()} {platform.machine()}; pass --rid")
    if system == "linux" and Path("/etc/alpine-release").exists():
        system = "linux-musl"
    return f"{system}-{architecture}"


def prepare_output(output):
    """Empties the output folder, refusing to delete a folder that is not a package made by this script."""
    if output.exists():
        if any(output.iterdir()) and not (output / MANIFEST).exists():
            fail(f"'{output}' is not empty and is not a MajSimai C++ package; choose another --output")
        shutil.rmtree(output)
    output.mkdir(parents=True)


def version_properties(arguments):
    """Gets the MSBuild property that overrides the version of MajSimai, or nothing to keep the one in MajSimai.csproj."""
    return [f"-p:Version={arguments.version}"] if arguments.version else []


def publish(arguments, runtime_identifier, temporary):
    """Publishes MajSimai with native AOT and returns the link items written by MajSimai.NativePackage.targets."""
    items_file = temporary / "link-items.txt"
    publish_folder = temporary / "publish"
    run([arguments.dotnet, "publish", PROJECT,
         "-c", arguments.configuration,
         "-f", arguments.framework,
         "-r", runtime_identifier,
         "-p:PublishAot=true",
         f"-p:NativeLib={'Shared' if arguments.kind == 'shared' else 'Static'}",
         f"-p:CustomAfterMicrosoftCommonTargets={LINK_TARGETS}",
         f"-p:MajSimaiLinkItemsFile={items_file}",
         *version_properties(arguments),
         "-o", publish_folder])
    if not items_file.exists():
        fail("the publish did not write the link items; is native AOT supported for this runtime identifier?")
    items = {"binary": [], "library": [], "system": [], "framework": []}
    for line in items_file.read_text(encoding="utf-8").splitlines():
        kind, _, value = line.partition("=")
        if kind in items and value:
            items[kind].append(value)
    if len(items["binary"]) != 1:
        fail("the publish did not name its native binary")
    return publish_folder, items


def copy_file(source, destination):
    if not source.is_file():
        fail(f"'{source}' does not exist")
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, destination)


def package_native(arguments, runtime_identifier, publish_folder, items, output):
    """Copies the native files into the package and returns the content of MajSimaiNative.json."""
    is_windows = runtime_identifier.startswith("win")
    is_apple = runtime_identifier.startswith(APPLE_PREFIXES)
    binary = Path(items["binary"][0])
    published = publish_folder / binary.name if (publish_folder / binary.name).is_file() else binary
    manifest = {
        "kind": arguments.kind,
        "runtimeIdentifier": runtime_identifier,
        "library": None,
        "runtimeLibrary": None,
        "dependencies": [],
        "systemLibraries": [],
        "linkOptions": [],
        "compileDefinitions": [],
    }
    if arguments.kind == "shared" and is_windows:
        # Programs link the import library and need the DLL next to them at run time.
        copy_file(published, output / "bin" / binary.name)
        copy_file(binary.with_suffix(".lib"), output / "lib" / binary.with_suffix(".lib").name)
        manifest["library"] = f"lib/{binary.with_suffix('.lib').name}"
        manifest["runtimeLibrary"] = f"bin/{binary.name}"
        manifest["compileDefinitions"] = ["MAJSIMAI_API=__declspec(dllimport)"]
    elif arguments.kind == "shared":
        copy_file(published, output / "lib" / binary.name)
        manifest["library"] = f"lib/{binary.name}"
    else:
        copy_file(published, output / "lib" / binary.name)
        manifest["library"] = f"lib/{binary.name}"
        for library in items["library"]:
            source = Path(library)
            destination = output / "lib" / "aot" / source.name
            if destination.exists():
                fail(f"two native AOT libraries are named '{source.name}'")
            copy_file(source, destination)
            manifest["dependencies"].append(f"lib/aot/{source.name}")
        manifest["systemLibraries"] = items["system"] + [f"-Wl,-framework,{name}" for name in items["framework"]]
        if not is_windows and not is_apple:
            manifest["linkOptions"] = ["-pthread"]
    return manifest


def generate(arguments, output):
    """Generates the C++ wrapper and the CMake file of the package."""
    run([arguments.dotnet, "run", "--project", GENERATOR, "-c", arguments.configuration, *version_properties(arguments), "--",
         "--output", output, "--native-manifest", output / MANIFEST])


def verify(arguments, output):
    """Builds and runs a small program that links the package with CMake."""
    cmake = shutil.which("cmake")
    if cmake is None:
        fail("--verify needs CMake on the path")
    with tempfile.TemporaryDirectory(prefix="majsimai-cpp-verify-") as folder:
        folder = Path(folder)
        (folder / "main.cpp").write_text(VERIFY_PROGRAM, encoding="utf-8")
        (folder / "CMakeLists.txt").write_text(f"""cmake_minimum_required(VERSION 3.15)
project(MajSimaiVerify LANGUAGES CXX)
if(MSVC AND "{arguments.kind}" STREQUAL "static")
    # The native AOT runtime of a static library is compiled with the static release C runtime (/MT).
    set(CMAKE_MSVC_RUNTIME_LIBRARY MultiThreaded)
endif()
add_subdirectory("{output.as_posix()}" majsimai)
add_executable(verify main.cpp)
target_link_libraries(verify PRIVATE MajSimai::MajSimaiCpp)
if(WIN32 AND "{arguments.kind}" STREQUAL "shared")
    add_custom_command(TARGET verify POST_BUILD
        COMMAND "${{CMAKE_COMMAND}}" -E copy_if_different "$<TARGET_FILE:MajSimai::Native>" "$<TARGET_FILE_DIR:verify>")
endif()
""", encoding="utf-8")
        build = folder / "build"
        run([cmake, "-S", folder, "-B", build, "-DCMAKE_BUILD_TYPE=Release"])
        run([cmake, "--build", build, "--config", "Release"])
        candidates = [build / "verify", build / "verify.exe", build / "Release" / "verify.exe"]
        program = next((candidate for candidate in candidates if candidate.is_file()), None)
        if program is None:
            fail("the verification program was not built")
        run([program])


def main():
    parser = argparse.ArgumentParser(description="Publishes MajSimai with native AOT and packages it with the C++ wrapper.")
    parser.add_argument("--kind", choices=["shared", "static"], required=True, help="build a shared or a static library")
    parser.add_argument("--rid", help="the .NET runtime identifier, such as linux-x64 or win-x64 (default: this computer)")
    parser.add_argument("--output", help="the package folder (default: artifacts/cpp/<rid>-<kind>)")
    parser.add_argument("--framework", default="net10.0", help="the target framework to publish (default: net10.0)")
    parser.add_argument("--configuration", default="Release", help="the build configuration (default: Release)")
    parser.add_argument("--dotnet", default="dotnet", help="the dotnet command (default: dotnet)")
    parser.add_argument("--version", help="the version of MajSimai to build, such as 3.0.1 (default: the one in MajSimai.csproj)")
    parser.add_argument("--verify", action="store_true", help="build and run a small CMake program that links the package")
    arguments = parser.parse_args()

    runtime_identifier = arguments.rid or host_runtime_identifier()
    default_output = REPOSITORY / "artifacts" / "cpp" / f"{runtime_identifier}-{arguments.kind}"
    output = Path(arguments.output).resolve() if arguments.output else default_output
    prepare_output(output)
    with tempfile.TemporaryDirectory(prefix="majsimai-cpp-") as temporary:
        publish_folder, items = publish(arguments, runtime_identifier, Path(temporary))
        manifest = package_native(arguments, runtime_identifier, publish_folder, items, output)
    (output / MANIFEST).write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    generate(arguments, output)
    if arguments.verify:
        verify(arguments, output)
    print(f"The MajSimai C++ package ({arguments.kind}, {runtime_identifier}) is in '{output}'.")
    print("Add it to a CMake project with add_subdirectory() and link MajSimai::MajSimaiCpp.")


if __name__ == "__main__":
    main()
