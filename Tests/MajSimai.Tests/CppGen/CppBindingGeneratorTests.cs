using System;
using System.IO;
using System.Linq;
using MajSimai.CppGen;
using Xunit;

namespace MajSimai.Tests.CppGen;

/// <summary>
/// Tests the generator end to end: the checked-in wrapper is up to date, and the command line writes and checks files.
/// </summary>
public sealed class CppBindingGeneratorTests : IDisposable
{
    /// <summary>
    /// A temporary output directory, deleted after each test.
    /// </summary>
    private readonly string _output = Path.Combine(Path.GetTempPath(), "MajSimai.CppGen.Tests." + Guid.NewGuid().ToString("N"));

    /// <summary>
    /// Gets the directory of the checked-in C++ wrapper.
    /// </summary>
    internal static string CheckedInWrapper => Program.FindDefaultOutput(AppContext.BaseDirectory);

    /// <summary>
    /// Deletes the temporary output directory.
    /// </summary>
    public void Dispose()
    {
        if (Directory.Exists(_output))
        {
            Directory.Delete(_output, recursive: true);
        }
    }

    /// <summary>
    /// Checked-in wrapper: is up to date with the native ABI.
    /// </summary>
    [Fact]
    public void CheckedInWrapper_IsUpToDateWithTheNativeAbi()
    {
        var files = CppBindingGenerator.Generate(CppBindingGenerator.ReadMajSimai());

        var outdated = OutputDirectory.Check(CheckedInWrapper, files);

        Assert.True(outdated.Count == 0, $"The C++ wrapper in Bindings/Cpp is out of date ({string.Join(", ", outdated)}). Run `dotnet run --project tools/MajSimai.CppGen`.");
    }

    /// <summary>
    /// Generate: writes the headers and the CMake file with LF line endings and a banner.
    /// </summary>
    [Fact]
    public void Generate_WritesTheHeadersAndTheCMakeFile()
    {
        var files = CppBindingGenerator.Generate(CppBindingGenerator.ReadMajSimai());

        Assert.Equal(new[]
        {
            "include/MajSimai/MajSimai.h",
            "include/MajSimai/MajSimai.Core.g.h",
            "include/MajSimai/MajSimai.ArrayView.g.h",
            "include/MajSimai/MajSimai.Model.g.h",
            "include/MajSimai/MajSimai.Views.g.h",
            "CMakeLists.txt",
        }, files.Select(f => f.RelativePath));
        Assert.All(files, f => Assert.DoesNotContain("\r", f.Content));
        Assert.All(files, f => Assert.EndsWith("\n", f.Content));
        Assert.All(files, f => Assert.Contains("Generated by MajSimai.CppGen from the native ABI of MajSimai 3.0.0.", f.Content));
    }

    /// <summary>
    /// Run: checks, writes, ignores line endings and removes stale headers.
    /// </summary>
    [Fact]
    public void Run_ChecksWritesIgnoresLineEndingsAndRemovesStaleHeaders()
    {
        Assert.Equal(Program.OutOfDate, Run("--output", _output, "--check"));
        Assert.Equal(Program.Success, Run("--output", _output));
        Assert.Equal(Program.Success, Run("--output", _output, "--check"));

        var core = Path.Combine(_output, "include", "MajSimai", "MajSimai.Core.g.h");
        File.WriteAllText(core, File.ReadAllText(core).Replace("\n", "\r\n"));
        Assert.Equal(Program.Success, Run("--output", _output, "--check"));

        var stale = Path.Combine(_output, "include", "MajSimai", "MajSimai.Old.g.h");
        var handWritten = Path.Combine(_output, "include", "MajSimai", "Extra.h");
        File.WriteAllText(stale, "// old");
        File.WriteAllText(handWritten, "// mine");
        var error = new StringWriter();
        Assert.Equal(Program.OutOfDate, Program.Run(new[] { "--output", _output, "--check" }, TextWriter.Null, error));
        Assert.Contains("Out of date: include/MajSimai/MajSimai.Old.g.h", error.ToString());

        File.AppendAllText(core, "// edited");
        var output = new StringWriter();
        Assert.Equal(Program.Success, Program.Run(new[] { "--output", _output }, output, TextWriter.Null));
        Assert.Contains("Updated include/MajSimai/MajSimai.Core.g.h", output.ToString());
        Assert.False(File.Exists(stale));
        Assert.True(File.Exists(handWritten));
        Assert.Equal(Program.Success, Run("--output", _output, "--check"));
    }

    /// <summary>
    /// Run: rejects unknown arguments.
    /// </summary>
    [Fact]
    public void Run_RejectsUnknownArguments()
    {
        var error = new StringWriter();

        Assert.Equal(Program.Failure, Program.Run(new[] { "--outptu", _output }, TextWriter.Null, error));
        Assert.Equal(Program.Failure, Program.Run(new[] { "--output" }, TextWriter.Null, TextWriter.Null));
        Assert.Contains("unknown or incomplete argument '--outptu'", error.ToString());
    }

    /// <summary>
    /// Find default output: finds Bindings/Cpp in the repository and fails outside it.
    /// </summary>
    [Fact]
    public void FindDefaultOutput_FindsTheWrapperInTheRepositoryAndFailsOutsideIt()
    {
        Directory.CreateDirectory(_output);

        Assert.True(File.Exists(Path.Combine(CheckedInWrapper, "..", "..", "MajSimai.csproj")));
        Assert.Throws<CppGenException>(() => Program.FindDefaultOutput(_output));
    }

    /// <summary>
    /// Runs the command line without capturing its output.
    /// </summary>
    /// <param name="args">The arguments.</param>
    /// <returns>The exit code.</returns>
    private static int Run(params string[] args)
    {
        return Program.Run(args, TextWriter.Null, TextWriter.Null);
    }
}
